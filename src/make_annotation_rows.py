import pandas as pd

ANNOTATOR = {
    "P1": ["tcs", "nestle", "cipla", "ambuja", "jswsteel",
           "hcltech", "mahindra", "ntpc", "hindalco", "itc"],
    "P2": ["infosys", "hindustanunilever", "sunpharma", "shreecement", "tatasteel",
           "drreddys", "ultratechcement", "marutisuzuki", "bajajauto", "powergrid"],
}
owner = {c: p for p, cs in ANNOTATOR.items() for c in cs}

NAMES = {
    "ambuja": "Ambuja Cements", "bajajauto": "Bajaj Auto", "cipla": "Cipla",
    "drreddys": "Dr. Reddy's Laboratories", "hcltech": "HCLTech",
    "hindalco": "Hindalco Industries", "hindustanunilever": "Hindustan Unilever",
    "infosys": "Infosys", "itc": "ITC", "jswsteel": "JSW Steel",
    "mahindra": "Mahindra & Mahindra", "marutisuzuki": "Maruti Suzuki",
    "nestle": "Nestle India", "ntpc": "NTPC", "powergrid": "Power Grid Corporation",
    "shreecement": "Shree Cement", "sunpharma": "Sun Pharmaceutical Industries",
    "tatasteel": "Tata Steel", "tcs": "Tata Consultancy Services",
    "ultratechcement": "UltraTech Cement",
}

FIELDS = [
    ("F01", "Total energy consumed", "What is the total energy consumed by {c}?"),
    ("F02", "Total electricity consumption", "What is the total electricity consumption of {c}?"),
    ("F03", "Scope 1 emissions", "What are the total Scope 1 emissions of {c}?"),
    ("F04", "Scope 2 emissions", "What are the total Scope 2 emissions of {c}?"),
    ("F05", "Scope 3 emissions", "What are the total Scope 3 emissions of {c}?"),
    ("F06", "Total water withdrawn", "What is the total water withdrawn by {c}?"),
    ("F07", "Total water discharged", "What is the total water discharged by {c}?"),
    ("F08", "Total waste generated", "What is the total waste generated by {c}?"),
    ("F09", "Hazardous waste generated", "How much hazardous waste was generated by {c}?"),
    ("F10", "Total employees", "What is the total number of employees of {c}?"),
    ("F11", "Women employees", "What is the number of women employees of {c}?"),
    ("F12", "Employee grievance mechanism", "Does {c} have an employee grievance mechanism?"),
]

comp = pd.read_csv("data/companies.csv")
comp["annotator"] = comp.company_id.map(owner)
assert comp.annotator.notna().all(), "a company has no annotator"
assert comp.annotator.value_counts().eq(10).all(), "each person must have 10"
comp.to_csv("data/companies.csv", index=False)

rows = []
for _, r in comp.sort_values(["annotator", "company_id"]).iterrows():
    for fid, fname, tmpl in FIELDS:
        rows.append({
            "row_id": f"{r.company_id}_{fid}", "company_id": r.company_id,
            "fold": r.fold, "fy": r.fy, "pdf_filename": r.pdf_filename,
            "field_id": fid, "field_name": fname,
            "question": tmpl.format(c=NAMES[r.company_id]),
            "status": "", "gold_value": "", "gold_unit": "", "page": "",
            "annotator": r.annotator, "notes": "", "reviewer": "", "review_agree": "",
        })

df = pd.DataFrame(rows)
assert len(df) == 240
df.to_csv("data/annotations.csv", index=False)
print(df.groupby("annotator").size())
